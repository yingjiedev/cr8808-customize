#!/bin/sh
# Template for the tested CR8808/xpa/ap-mp02.1 stock layout and pinned image.
# Generate a per-device copy with prepare-cr8808-flash.ps1. Default: check only.
set -eu
PHASE=preflight
fail() { echo "STOP [$PHASE]: $*" >&2; exit 1; }
MODE=--check
[ "$#" -le 1 ] || fail 'Usage: sh script.sh [--check|--flash]'
if [ "$#" -eq 1 ]; then MODE=$1; fi
case "$MODE" in --check|--flash) ;; *) fail 'Use --check or --flash' ;; esac

MIBIB_SHA256='__MIBIB_SHA256__'
APPSBL_SHA256='__APPSBL_SHA256__'
ART_SHA256='__ART_SHA256__'
ROOTFS_SHA256='__ROOTFS_SHA256__'
for checksum in "$MIBIB_SHA256" "$APPSBL_SHA256" "$ART_SHA256" "$ROOTFS_SHA256"; do
    case "$checksum" in ''|*[!0-9a-f]*) fail 'Unfilled template: run prepare-cr8808-flash.ps1 first' ;; esac
    [ "${#checksum}" -eq 64 ] || fail 'Invalid backup SHA256'
done

IMAGE=/tmp/cr880x-factory.ubi
IMAGE_SHA256=897fd05dd6584e820aeb99905191dd8532564758c12db486e8041625d00797e7
PAGES_SHA256=1800e2bbdfb0aa76e81497c555c2c8122c980af75b33eddf158e0ceac4d4bf08
for tool in openssl ubiformat nvram awk dd strings tr grep sed head wc id cat; do
    command -v "$tool" >/dev/null || fail "Missing tool: $tool"
done
[ "$(id -u)" = 0 ] || fail 'Root access required'
[ "$(nvram get model)" = CR8808 ] || fail 'Unexpected original model'
[ "$(cat /tmp/sysinfo/board_name)" = ap-mp02.1 ] || fail 'Unexpected board'
tr '\000' '\n' < /proc/device-tree/compatible | grep -qx 'qcom,ipq5018-mp02.1' || fail 'Unexpected device tree'
[ "$(strings /dev/mtdblock15 | sed -n 's/^wl_pa_type=//p' | head -n 1)" = xpa ] || fail 'Only the tested xpa hardware route is covered'
[ "$(awk '$4 == "\"rootfs\"" {print $1, $2}' /proc/mtd)" = 'mtd18: 02400000' ] || fail 'Unexpected rootfs layout'
[ "$(awk '$4 == "\"rootfs_1\"" {print $1, $2}' /proc/mtd)" = 'mtd19: 02400000' ] || fail 'Unexpected rootfs_1 layout'
[ "$(sed -n 's/.*ubi\.mtd=\([^ ]*\).*/\1/p' /proc/cmdline)" = rootfs ] || fail 'This route requires the active stock rootfs/mtd18 slot'
[ "$(nvram get flag_boot_rootfs)" = 0 ] || fail 'Unexpected boot flag'
[ "$(nvram get flag_last_success)" = 0 ] || fail 'Unexpected last-success flag'
[ "$(cat /sys/class/mtd/mtd19/type)" = nand ] || fail 'Target is not NAND'
[ "$(cat /sys/class/mtd/mtd19/writesize)" = 2048 ] || fail 'Unexpected NAND page size'
[ "$(cat /sys/class/mtd/mtd19/erasesize)" = 131072 ] || fail 'Unexpected NAND erase size'
[ "$(cat /sys/class/mtd/mtd19/oobsize)" = 64 ] || fail 'Unexpected NAND OOB size'
for entry in /sys/class/ubi/ubi[0-9]*/mtd_num; do
    [ -f "$entry" ] || continue
    [ "$(cat "$entry")" != 19 ] || fail 'Target mtd19 is attached to UBI'
done
[ -s "$IMAGE" ] || fail 'Firmware file missing'
[ "$(wc -c < "$IMAGE" | tr -d ' ')" = 17694720 ] || fail 'Firmware length mismatch'
check_hash() {
    actual=$(openssl dgst -sha256 "$1" | awk '{print $NF}')
    [ "$actual" = "$2" ] || fail "Hash mismatch: $1"
}
check_hash "$IMAGE" "$IMAGE_SHA256"
check_hash /dev/mtd1 "$MIBIB_SHA256"
check_hash /dev/mtd11 "$APPSBL_SHA256"
check_hash /dev/mtd13 "$ART_SHA256"
check_hash /dev/mtd18 "$ROOTFS_SHA256"
echo 'PREFLIGHT_OK: active=rootfs/mtd18 target=rootfs_1/mtd19'
if [ "$MODE" = --check ]; then
    echo 'CHECK_ONLY_COMPLETE: no flash or boot-flag writes'
    exit 0
fi

PHASE=write
ubiformat /dev/mtd19 -y -f "$IMAGE" || fail 'ubiformat failed; do not reboot'
PHASE=readback
# EC headers are regenerated by ubiformat. Compare the subsequent pages of
# the fixed 135-PEB image. A shifted bad block or short read stops boot switching.
READBACK=$(
    (
        block=0
        while [ "$block" -lt 135 ]; do
            dd if=/dev/mtd19 bs=2048 skip=$((block * 64 + 1)) count=63 2>/dev/null || exit 1
            block=$((block + 1))
        done
    ) | openssl dgst -sha256 | awk '{print $NF}'
)
[ "$READBACK" = "$PAGES_SHA256" ] || fail 'Readback mismatch; boot flags not changed; do not reboot'
echo "READBACK_PAGES_SHA256_OK: $READBACK"
PHASE=boot-flags
nvram set flag_try_sys2_failed=0 || fail 'Failed to set boot flag'
nvram set flag_boot_rootfs=1 || fail 'Failed to set boot flag'
nvram set flag_last_success=1 || fail 'Failed to set last-success flag'
nvram commit || fail 'Failed to commit boot flags; do not reboot'
sync
[ "$(nvram get flag_try_sys2_failed)" = 0 ] || fail 'Boot-flag verification failed'
[ "$(nvram get flag_boot_rootfs)" = 1 ] || fail 'Boot-flag verification failed'
[ "$(nvram get flag_last_success)" = 1 ] || fail 'Boot-flag verification failed'
echo 'FLASH_AND_BOOT_FLAGS_COMPLETE: inspect output, then run reboot separately'
